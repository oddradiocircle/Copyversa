export function createI18n(language = 'es') {
    const lang = language.toLowerCase().startsWith('es') ? 'es' : 'en';
    const messages = MESSAGES[lang];

    const t = (key, vars = {}) =>
        (messages[key] ?? key).replace(/\{(\w+)\}/g, (match, name) => vars[name] ?? match);

    t.lang = lang;
    t.tag = (tagName) => {
        const name = /^h[1-6]$/.test(tagName) ? 'heading' : tagName;
        return messages[`tag.${name}`] ?? messages['tag.default'];
    };
    t.date = (date) => new Intl.DateTimeFormat(lang, { dateStyle: 'long' }).format(date);
    return t;
}
